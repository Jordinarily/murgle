function Sound.AreAllMuted()
    for _, key in ipairs(toggles) do
        if MurgleDB.sound[key] ~= true then
            return false
        end
    end
    return true
end

function Sound.SetAllMuted(enabled)
    for _, key in ipairs(toggles) do
        MurgleDB.sound[key] = enabled == true
    end
    Sound.ApplyAll()
end

function Sound.Initialize()
    Sound.ApplyAll()
end
