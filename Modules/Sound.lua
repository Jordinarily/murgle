local extraMuted = {}

local function applySpeech()
    local settings = MurgleDB.sound
    if settings.muteErrorSpeech ~= true and speechPrior == nil and settings.errorSpeechRestore == nil then
        return
    end
    if type(GetCVar) ~= "function" or type(SetCVar) ~= "function" then
        return
    end
    local current = GetCVar("Sound_EnableErrorSpeech")
    if current ~= "0" and current ~= "1" then
        return
    end
    if settings.muteErrorSpeech == true then
        if speechPrior ~= nil then
            return
        end
        local saved = settings.errorSpeechRestore
        speechPrior = (saved == "0" or saved == "1") and saved or current
        settings.errorSpeechRestore = speechPrior
        if current ~= "0" then
            SetCVar("Sound_EnableErrorSpeech", "0")
        end
    else
        local prior = speechPrior or settings.errorSpeechRestore
        if current == "0" and (prior == "0" or prior == "1") and current ~= prior then
            SetCVar("Sound_EnableErrorSpeech", prior)
        end
        speechPrior, settings.errorSpeechRestore = nil, nil
    end
end

local function applyFiles(files, mute, owned)
    if mute == owned then
        return owned
    end
    if type(UnmuteSoundFile) ~= "function" or mute and type(MuteSoundFile) ~= "function" then
        return owned
    end
    local apply = mute and MuteSoundFile or UnmuteSoundFile
    for _, id in ipairs(files) do
        apply(id)
    end
    -- There is no verified prior-mute getter/token. Release only our applied
    -- groups, but another addon's overlapping mute cannot be distinguished.
    return mute
end

function Sound.ApplyAll()
    applySpeech()
    fizzleMuted = applyFiles(fizzleFiles, MurgleDB.sound.muteFizzle == true, fizzleMuted)
    trainsMuted = applyFiles(trainFiles, MurgleDB.sound.muteTrains == true, trainsMuted)
    mechanicalMuted = applyFiles(mechanicalFiles, MurgleDB.sound.muteMechanicalSteps == true, mechanicalMuted)
    for key, files in pairs(extraFiles) do
        extraMuted[key] = applyFiles(files, MurgleDB.sound[key] == true, extraMuted[key] == true)
    end
end

local toggles = {
    "muteFizzle",
    "muteTrains",
    "muteMechanicalSteps",
    "muteErrorSpeech",
