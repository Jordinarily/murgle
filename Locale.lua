local OVERRIDES = {
    -- Only verified human translations belong here; English is complete.
}

local locale = GetLocale and GetLocale() or "enUS"
local L = {}
for key, value in pairs(EN) do
    L[key] = value
end
local override = OVERRIDES[locale]
if override then
    for key, value in pairs(override) do
        L[key] = value
    end
end
Murgle.L = L

function Murgle.GetString(key)
    return L[key] or EN[key] or key
end
