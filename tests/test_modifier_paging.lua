test("paging refuses a custom modifier resolver introduced by another owner", function()
    P.withPaging(function(M, s, label)
        MurgleDB.interface.holdActionPages = true
        M.ApplyAll()
        s.buttons[1]:SetAttribute("modifiers", "SELFCAST:self")
        s:modifiers(true)
        eq(M.IsActive(), false)
        eq(next(s.bindings), nil)
        eq(s.buttons[1]:GetAttribute("modifiers"), "SELFCAST:self")
        eq(s.buttons[2]:GetAttribute("actionpage"), nil)
    end)
end)

