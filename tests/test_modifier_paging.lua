    end, 2)
end)
test("paging label survives native writes and native manual pages suspend overrides", function()
    P.withPaging(function(M, s, label)
        MurgleDB.interface.holdActionPages = true
        M.ApplyAll()
        s:modifiers(true)
        label:SetText(1)
        eq(label:GetText(), "2")
        C_ActionBar.SetActionBarPage(3)
        s:drive()
        eq(s.buttons[1].rendered, 25)
        eq(label:GetText(), "3")
        eq(next(s.bindings), nil)
        C_ActionBar.SetActionBarPage(1)
        s:drive()
        eq(s.buttons[1].rendered, 13)
        eq(label:GetText(), "2")
        MurgleDB.interface.holdActionPages = false
        M.ApplyAll()
        eq(label:GetText(), "1")
        eq(s.buttons[1].rendered, 1)
        eq(next(s.bindings), nil)
        eq(next(s.drivers), nil)
    end)
end)
test("paging modifier transitions stay secure in combat and cleanup defers", function()
