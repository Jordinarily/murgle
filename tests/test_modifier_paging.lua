local P = dofile("tests/paging_helpers.lua")
test("repaired paging ignores old enabled flag and does nothing at disabled startup", function()
    P.withPaging(function(M, s)
        MurgleDB.interface.modifierPaging = true
        M.ApplyAll()
        eq(#s.frames, 0)
        eq(s.hooks, nil)
        eq(next(s.drivers), nil)
    end)
end)
test("paging Shift alone changes actions indicator and bound input both ways repeatedly", function()
    P.withPaging(function(M, s, label)
        MurgleDB.interface.holdActionPages = true
        M.ApplyAll()
        for attempt = 1, 3 do
            s:modifiers(true)
            eq(s.buttons[1].rendered, 13)
            eq(label:GetText(), "2")
            local action, command = s:press("SHIFT-1")
            eq(action, 13)
            eq(command, "ACTIONBUTTON1")
            s:modifiers(false)
            eq(s.buttons[1].rendered, 1)
            eq(label:GetText(), "1")
            eq(s:press("1"), 1)
        end
        eq(s.saved["SHIFT-1"], "ACTIONPAGE1")
    end)
end)
test("paging starts from native page one when explicitly enabled on page two", function()
    P.withPaging(function(M, s, label)
        MurgleDB.interface.holdActionPages = true
        M.ApplyAll()
