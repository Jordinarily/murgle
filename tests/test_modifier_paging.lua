test("rebinding while Shift is held replaces only temporary modified keys and preserves page two", function()
    P.withPaging(function(M, s, label)
        MurgleDB.interface.holdActionPages = true
        M.ApplyAll()
        s:modifiers(true)
        GetBindingKey = function(command)
            if command == "ACTIONBUTTON1" then
                return "Q"
            end
        end
        s.frames[2].scripts.OnEvent(s.frames[2], "UPDATE_BINDINGS")
        eq(s.bindings["SHIFT-1"], nil)
        eq(s.bindings["SHIFT-Q"], "ACTIONBUTTON1")
        eq(s:press("SHIFT-Q"), 13)
        eq(s.buttons[1].rendered, 13)
        eq(label:GetText(), "2")
        eq(s.saved["SHIFT-1"], "ACTIONPAGE1")
    end)
end)
test("reapply during a manually selected native page does not reset it to page one", function()
