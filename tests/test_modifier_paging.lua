test("paging reapply keeps one driver and one indicator hook and clears all work on disable", function()
    P.withPaging(function(M, s, label)
        MurgleDB.interface.holdActionPages = true
        M.ApplyAll()
        M.ApplyAll()
        eq(#s.frames, 2)
        eq(s.hooks, 1)
        local drivers = 0
        for _ in pairs(s.drivers) do
            drivers = drivers + 1
        end
        eq(drivers, 1)
        s:modifiers(true)
        MurgleDB.interface.holdActionPages = false
        M.ApplyAll()
        eq(M.IsActive(), false)
        eq(next(s.bindings), nil)
        eq(next(s.drivers), nil)
        for _, f in ipairs(s.frames) do
            eq(next(f.events), nil)
        end
        label:SetText(4)
        eq(label:GetText(), "4", "disabled hook must be inert")
    end)
end)
test("paging refuses foreign attributes and does not overwrite a new owner during transitions", function()
    P.withPaging(function(M, s, label)
        MurgleDB.interface.holdActionPages = true
        s.buttons[1]:SetAttribute("shift-actionpage", 5)
        M.ApplyAll()
        eq(#s.frames, 0)
        s.buttons[1]:SetAttribute("shift-actionpage", nil)
        M.ApplyAll()
        s:modifiers(true)
        s.buttons[1]:SetAttribute("actionpage", 5)
        s:modifiers(false, true)
        eq(s.buttons[1]:GetAttribute("actionpage"), 5)
        eq(M.IsActive(), false)
        eq(next(s.bindings), nil)
        MurgleDB.interface.holdActionPages = false
        M.ApplyAll()
        eq(s.buttons[1]:GetAttribute("actionpage"), 5)
    end)
end)
